import type { NextRequest } from "next/server";

import { PHOTO_BUCKET } from "@/lib/photos/constants";
import { isBoundedList, isPersonKey, isPhotoExtension, isUuid } from "@/lib/photos/validation";
import { isCrossSiteRequest, readJsonBody } from "@/lib/server/request-guards";
import { getAdminClient } from "@/lib/supabase/admin";

const MAX_BODY_BYTES = 8 * 1024;

function reply(body: unknown, status: number) {
  return Response.json(body, { status, headers: { "Cache-Control": "no-store" } });
}

/**
 * Guest photo slots. The submission's idempotency key (generated in the
 * browser, known only to the submitter) is the capability; the database
 * checks it belongs to a pending application < 24 h old, that each person
 * exists on it, and caps open reservations per person.
 * Paths are generated by the database; the client never chooses one.
 */
export async function POST(request: NextRequest) {
  if (isCrossSiteRequest(request)) return reply({ ok: false, message: "Request not allowed." }, 403);

  const body = (await readJsonBody(request, MAX_BODY_BYTES)) as
    | { idempotencyKey?: unknown; personKeys?: unknown; ext?: unknown }
    | undefined;
  if (
    !body ||
    !isUuid(body.idempotencyKey) ||
    !isBoundedList(body.personKeys, isPersonKey) ||
    !isPhotoExtension(body.ext)
  ) {
    return reply({ ok: false, message: "Invalid request." }, 400);
  }

  const supabase = getAdminClient();
  const { data, error } = await supabase.rpc("reserve_application_photos", {
    p_idempotency_key: body.idempotencyKey,
    p_person_keys: body.personKeys,
    p_extension: body.ext,
  });

  if (error) {
    console.error("[photos] reserve failed", error.code, error.message);
    const map: Record<string, [number, string]> = {
      PT404: [404, "We couldn’t find this application. Photos can be added right after submitting."],
      PT409: [409, "Photos can no longer be added online for this application. Please contact the community office."],
      PT429: [429, "Too many upload attempts for this person. Please contact the community office."],
      PT422: [422, "Invalid photo request."],
    };
    const [status, message] = map[error.code] ?? [502, "Photo uploads aren’t available right now. Try again."];
    return reply({ ok: false, message }, status);
  }

  const rows = (data ?? []) as Array<{ person_key: string; storage_path: string }>;
  const bucket = supabase.storage.from(PHOTO_BUCKET);
  const items: Array<{ personKey: string; path: string; signedUrl: string }> = [];

  for (const row of rows) {
    // upsert stays false: the signed URL can only create, never overwrite.
    const { data: signed, error: signError } = await bucket.createSignedUploadUrl(row.storage_path);
    if (signError || !signed) {
      console.error("[photos] could not sign upload", signError?.message);
      continue; // the reservation simply expires; the client reports this person as failed
    }
    items.push({ personKey: row.person_key, path: row.storage_path, signedUrl: signed.signedUrl });
  }

  if (items.length === 0) {
    return reply({ ok: false, message: "Photo uploads aren’t available right now. Try again." }, 502);
  }
  return reply({ ok: true, items }, 200);
}
